/**
 * GET /api/health/quota — สัญญาณ "โควตาผู้ให้บริการใกล้หมด"
 *
 * ══════════════════════════════════════════════════════════════════
 * ทำไมต้องเป็น endpoint แยกจาก /api/health/tracking
 *
 * สองเรื่องนี้เป็นคนละชนิดกันโดยสิ้นเชิง และต้องการการตอบสนองคนละแบบ:
 *
 *   /api/health/tracking  "ผู้ใช้ใช้เว็บไม่ได้ตอนนี้" → ต้องรีบดูเดี๋ยวนี้
 *   /api/health/quota     "อีกไม่นานจะหมดโควตา"     → วางแผนได้ ไม่ต้องรีบ
 *
 * เดิมทั้งสองออกทางท่อเดียวกัน ผลคือ monitor รายงาน DOWN ติดกัน 61 ชั่วโมง
 * เพราะโควตา ทั้งที่เว็บใช้งานได้ปกติทุกวินาที แล้วจบลงที่การปิดปากมันทิ้ง —
 * ซึ่งแปลว่าตั้งแต่วันนั้นเราก็ไม่มีทางรู้เรื่องโควตาอีกเลย
 *
 * ══════════════════════════════════════════════════════════════════
 * ⚠️ ตอบ 503 เฉพาะเจ้าที่ **รอบบิลรีเซ็ตได้** (daily / monthly)
 *
 * เจ้าที่ไม่มีวันรีเซ็ต (lifetime) ถ้าเอามาใส่ที่นี่ด้วย มันจะ 503 ค้างตลอดกาล
 * ตั้งแต่วินาทีที่ข้ามเกณฑ์ เพราะไม่มีอะไรทำให้ตัวเลขลดลงได้อีก = สร้างปัญหา
 * 61 ชั่วโมงขึ้นมาใหม่ในช่องทางใหม่ แล้วเราก็จะปิดปากมันอีกรอบ
 *
 * เจ้าแบบนั้นไปแสดงบน /admin/stats แทน พร้อมบอกว่าเหลืองบค้นหาเท่าไร —
 * เป็นสภาพถาวรที่รอการตัดสินใจ (จะซื้อเพิ่มไหม) ไม่ใช่เหตุการณ์ที่จะหายไปเอง
 *
 * การแยกอิงจาก readPeriod().cycle ซึ่งเป็นข้อมูลที่ระบบมีอยู่แล้ว **ไม่ได้
 * ฮาร์ดโค้ดชื่อเจ้าไว้ที่ไหนเลย** เจ้าใหม่ที่เป็น lifetime จึงเข้ากฎนี้เอง
 * อัตโนมัติ (ดู lib/health-check.ts และเทสต์ที่เฝ้าข้อนี้)
 * ══════════════════════════════════════════════════════════════════
 *
 * อ่านผลจาก HTTP status เหมือน endpoint พี่น้องของมัน:
 *   200  โควตาที่รีเซ็ตได้ยังไม่มีเจ้าไหนใกล้ชนเพดาน
 *   503  มีเจ้าที่ใกล้ชนแล้ว — monitor เดิมแจ้งเตือนให้เองโดยไม่ต้องเพิ่มบริการใหม่
 *
 * ตั้ง monitor ความถี่ต่ำได้ (ชั่วโมงละครั้งก็พอ) เพราะโควตาขยับช้า และ
 * ยิ่งถี่ยิ่งเปลืองโดยไม่ได้อะไรเพิ่ม
 */

import { NextResponse } from "next/server";

import {
  judgeQuota,
  quotaLogLine,
  recoverableQuotaAlerts,
  standingQuotaWarnings,
} from "@/lib/health-check";
import { loadProviderUsage } from "@/lib/provider-usage";

/** ต้องรันบน Node.js runtime เพราะอ่าน env และคุยกับ Supabase ด้วย service role */
export const runtime = "nodejs";
/** ห้าม cache — คำตอบที่ค้างอยู่คือคำตอบที่บอกว่า "ปกติ" ทั้งที่หมดไปแล้ว */
export const dynamic = "force-dynamic";

export async function GET() {
  // ยอดใน memory เป็นศูนย์หลัง restart ต้องอ่านของจริงก่อนตัดสิน
  // ไม่งั้น endpoint นี้จะรายงานว่าโควตายังว่างทุกครั้งที่เพิ่ง deploy เสร็จ
  await loadProviderUsage();

  const recoverable = recoverableQuotaAlerts();
  const standing = standingQuotaWarnings();
  const verdict = judgeQuota();

  // ⚠️ log ทุกครั้ง ไม่ใช่เฉพาะตอนผิดปกติ — ต่างจาก /api/health/tracking โดยตั้งใจ
  //
  // เจ้าแบบ lifetime ที่หมดโควตาไปแล้วจะไม่ทำให้ status เป็น 503 เลยตลอดกาล
  // ถ้า log เฉพาะตอน 503 มันจะเงียบสนิททั้งใน monitor และใน log ซึ่งคือการย้าย
  // จุดบอดไปที่ใหม่ ไม่ใช่การแก้ · endpoint นี้ถูกยิงชั่วโมงละครั้ง log จึงไม่ท่วม
  console.info(quotaLogLine(recoverable, standing));

  return NextResponse.json(
    {
      status: verdict.ok ? ("ok" as const) : ("degraded" as const),
      ...(verdict.ok ? {} : { reason: verdict.reason }),
      /** เจ้าที่ใกล้ชนเพดานและรอบบิลรีเซ็ตได้ — กลุ่มที่ทำให้ status เป็น 503 */
      alerts: recoverable,
      /**
       * เจ้าที่ใกล้ชนเพดานแต่ไม่มีวันรีเซ็ต — ไม่ทำให้ 503 โดยตั้งใจ
       * มีในคำตอบเพื่อให้คนที่เปิดดูด้วยตาเห็นครบ ไม่ใช่ซ่อนไว้
       */
      standing,
    },
    {
      status: verdict.ok ? 200 : 503,
      headers: { "Cache-Control": "no-store" },
    },
  );
}
