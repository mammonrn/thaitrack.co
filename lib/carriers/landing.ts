/** คำถาม-คำตอบหนึ่งข้อบนหน้า landing (ไปเป็น JSON-LD ด้วย) */
export interface LandingFaq {
  question: string;
  answer: string;
}

export interface CarrierLanding {
  /**
   * ส่วนท้ายของ URL — เป็นภาษาไทยตามแผน เช่น "เช็คพัสดุ-flash"
   *
   * Next.js รองรับ dynamic segment เฉพาะทั้ง segment (โฟลเดอร์ต้องชื่อ [param]
   * เป๊ะๆ) จะทำโฟลเดอร์ชื่อ "เช็คพัสดุ-[carrier]" ไม่ได้ เราจึงใช้ [carrier]
   * ที่ระดับบนสุดแล้วให้ slug ทั้งก้อนเป็นค่าของมัน พร้อมปิด dynamicParams
   * เพื่อให้ path ที่ไม่อยู่ในรายการนี้ตอบ 404 แทนที่จะพยายาม render
   */
  slug: string;
  /** ชื่อที่ใช้ในเนื้อหา */
  name: string;
  /**
   * หัวข้อ H1 เต็มๆ — เขียนแยกเพราะการเว้นวรรคภาษาไทยกับอังกฤษไม่เหมือนกัน
   *
   * "เช็คพัสดุไปรษณีย์ไทย" ติดกันถูกแล้ว แต่ "เช็คพัสดุFlash" ผิด ต้องมีช่องว่าง
   * ก่อนคำอังกฤษ — กติกาแบบนี้เขียนเป็นเงื่อนไขในโค้ดได้ไม่ครบทุกกรณี
   * จึงให้เขียนข้อความที่ต้องการตรงๆ ไปเลย
   */
  heading: string;
  /** ชื่อทางการเต็ม ใช้ใน JSON-LD */
  fullName: string;
  /**
   * courierCode ที่ส่งไปเป็นตัวช่วยเดาให้เซิร์ฟเวอร์ — null เมื่อไม่ควรส่ง
   *
   * ไปรษณีย์ไทยเป็น null เพราะเราต่อตรงกับ API ของเขาอยู่แล้วและถูกถามก่อน
   * ทุกครั้งที่ prefix เดาไม่ออก การส่ง hint จึงไม่เปลี่ยนอะไรเลย
   */
  courierCode: string | null;
  /** ประโยคใต้ H1 */
  intro: string;
  /** ตัวอย่างเลขพัสดุใน placeholder ของช่องกรอก */
  placeholder: string;
  /** คำอธิบายรูปแบบเลขพัสดุ — เขียนเฉพาะที่ยืนยันแล้ว */
  numberFormat: string;
  /** คำอธิบายสำหรับ meta description */
  description: string;
  faqs: LandingFaq[];
}

