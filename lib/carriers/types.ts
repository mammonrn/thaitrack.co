/** เหตุการณ์หนึ่งบรรทัดใน timeline การเดินทางของพัสดุ */
export interface TrackingEvent {
  /** เวลาที่เกิดเหตุการณ์ รูปแบบ ISO 8601 เช่น "2026-08-30T09:12:00+07:00" */
  time: string;
  /** สถานที่ เช่น "ศูนย์ไปรษณีย์หลักสี่" ("" ถ้าขนส่งไม่ได้ส่งมา) */
  location: string;
  /** คำบรรยายเหตุการณ์เป็นภาษาไทย */
  description: string;
  /**
   * ที่อยู่เต็มของสถานที่ในบรรทัดนี้ ถ้าขนส่งส่งมาด้วย — ไม่แสดงให้ผู้ใช้เห็น
   *
   * ขนส่งส่วนใหญ่ให้มาแค่รหัสสาขา ("ACRAI-B - เมืองเชียงราย") ซึ่ง Google
   * ไม่รู้จัก แต่บางเจ้าห้อยที่อยู่เต็มมาท้ายข้อความด้วย นั่นคือวัตถุดิบเดียว
   * ที่ทำให้เติมพิกัดสาขาลงตารางของกลางได้เอง (ดู lib/branch-harvest.ts)
   *
   * ฟิลด์นี้เพิ่มทีหลัง ข้อมูลเก่าใน cache จึงไม่มี ทุกที่ที่อ่านต้องรับ
   * undefined ได้ด้วย ไม่ใช่แค่ null
   */
  address?: string | null;
}

/**
 * รายละเอียดการจัดส่งที่ขนส่งบางเจ้าส่งมาให้ — ทุกฟิลด์ขาดได้
 *
 * ขนส่งแต่ละเจ้าให้ข้อมูลไม่เท่ากัน และฟิลด์ที่ให้มาก็ว่างได้ UI จึงต้องแสดง
 * เฉพาะฟิลด์ที่มีค่าจริง ห้ามเว้นช่องว่างไว้หรือเติมคำว่า "ไม่ระบุ" ให้เต็ม
 *
 * ⚠️ ตั้งใจไม่มีชื่อผู้รับ ผู้เซ็นรับ ที่อยู่ และเบอร์โทร แม้ปลายทางจะส่งมาก็ตาม
 * เพราะการค้นหาในเว็บนี้ไม่ต้องพิสูจน์ตัวตนอะไรเลย ใครก็ตามที่เห็นเลขพัสดุ
 * (บนกล่อง ในกลุ่มแชท ในอีเมลยืนยันคำสั่งซื้อ) จะได้ชื่อและที่อยู่คนรับไปทันที
 * ข้อมูลที่เก็บไว้ตรงนี้จึงจำกัดเฉพาะเรื่องของ "พัสดุ" ไม่ใช่เรื่องของ "คน"
 */
export interface ShipmentDetails {
  /** จังหวัดต้นทาง */
  originProvince: string | null;
  /** จังหวัดปลายทาง */
  destinationProvince: string | null;
  /** ชื่อพนักงานที่นำจ่าย — ข้อมูลเชิงบริการ ไม่ใช่ตัวตนของผู้รับ */
  deliveryStaffName: string | null;
  /** กำหนดส่งถึง (YYYY-MM-DD) */
  dueDate: string | null;
  /** ยอดเก็บเงินปลายทาง — null เมื่อไม่มีการเก็บเงินปลายทาง */
  cashOnDelivery: string | null;
  /** ระดับบริการที่ใช้ส่ง เช่น "On-Time Delivery" */
  deliveryType: string | null;
  /** เบอร์คอลเซ็นเตอร์ของขนส่ง — สิ่งแรกที่ผู้ใช้ต้องการเมื่อพัสดุมีปัญหา */
  callCenterPhone: string | null;
  /**
   * เบอร์ของสาขาที่นำจ่าย เช่น "052-020-230" — **เบอร์บริษัท ไม่ใช่ของบุคคล**
   *
   * มีเพราะคอลเซ็นเตอร์กลางตอบเรื่องพัสดุใบหนึ่งไม่ได้ คนที่รู้จริงคือสาขา
   * ที่ถือพัสดุอยู่ · ฟิลด์นี้คือคำตอบของ "แล้วจะติดต่อใคร" โดยไม่ต้องเปิดเผย
   * เบอร์มือถือส่วนตัวของพนักงานส่งของ (ซึ่งเราตั้งใจไม่แตะ — ดูเหตุผลเต็มที่
   * deliveryStaffPhoneNumber ใน lib/carriers/etrackings.ts)
   *
   * ฟิลด์นี้เพิ่มทีหลัง ข้อมูลเก่าใน cache จึงไม่มี ทุกที่ที่อ่านต้องรับ
   * undefined ได้ด้วย ไม่ใช่แค่ null
   */
  deliveryBranchPhone?: string | null;
  /**
   * ผู้ส่ง — แสดงเต็ม
   *
   * ต่างจากผู้รับตรงที่ช่องนี้แทบทั้งหมดเป็นชื่อร้านค้าหรือชื่อบัญชีขายของ
   * ซึ่งเป็นข้อมูลที่ร้านเปิดเผยต่อสาธารณะอยู่แล้ว และเป็นสิ่งที่ผู้ซื้อต้องใช้
   * ระบุว่าเป็นของจากคำสั่งซื้อไหน
   */
  sender: string | null;
  /**
   * ผู้รับ **ที่ปิดบังบางส่วนแล้ว** เช่น "ภูมิ ธ***"
   *
   * ⚠️ ชื่อฟิลด์ลงท้ายด้วย Masked โดยตั้งใจ เพื่อให้การเผลอเอาค่าเต็มมาใส่
   * อ่านแล้วผิดทันทีตั้งแต่ตอนเขียน ค่าเต็มถูกปิดตั้งแต่ใน adapter และไม่เคย
   * ออกมาถึงตรงนี้ (ดู lib/mask-name.ts)
   */
  recipientMasked: string | null;
  /** ผู้เซ็นรับ **ที่ปิดบังบางส่วนแล้ว** — กติกาเดียวกับ recipientMasked */
  signerMasked: string | null;
}

/**
 * ข้อมูลที่ **ห้ามเก็บลง cache และห้ามส่งให้คนที่ไม่มีสิทธิ์**
 *
 * แยกออกมาเป็นก้อนของตัวเองแทนที่จะปนอยู่ใน ShipmentDetails เพราะสองอย่าง:
 *
 *   1. การลบทิ้งก่อนเขียน cache เหลือแค่ลบคีย์เดียว (ดู rememberTracking)
 *      ไม่ต้องไล่ลบทีละฟิลด์ ซึ่งเป็นงานที่พลาดได้เมื่อมีคนเพิ่มฟิลด์ใหม่
 *   2. อ่านโค้ดแล้วเห็นทันทีว่าอะไรอ่อนไหว โดยไม่ต้องไปไล่อ่าน doc ของแต่ละฟิลด์
 *
 * tracking_cache เป็นของกลางที่ทุกคนที่ค้นเลขเดียวกันใช้ร่วมกัน ของในนี้จึงต้อง
 * ไม่มีวันไปอยู่ในนั้น — มีเทสต์เฝ้าไว้ที่ lib/sensitive-data.test.ts
 */
export interface SensitiveDetails {
  /**
   * รูปถ่ายตอนนำจ่าย — มักติดใบปะหน้าที่มีที่อยู่เต็มของผู้รับมาด้วย
   *
   * เห็นได้เฉพาะคนที่บันทึกพัสดุนี้ไว้ก่อนมันถึงมือผู้รับ (ดู lib/proof-access.ts)
   *
   * เป็นรายการเพราะขนส่งบางเจ้าส่งมาหลายรูป (J&T ส่งรูปพัสดุกับรูปลายเซ็น
   * มาในฟิลด์เดียวคั่นด้วยจุลภาค) รายการว่าง = ไม่มีรูป ไม่ใช่ null
   *
   * ⚠️ เป็น signed URL ที่หมดอายุใน 24 ชม. — ต้องดึงสดทุกครั้งที่จะแสดง
   * ห้ามเก็บไว้ใช้ใหม่ (ซึ่งรับประกันอยู่แล้วโดย withoutSensitive ใน
   * lib/tracking-cache.ts ที่ตัดคีย์ sensitive ทิ้งก่อนเขียน cache เสมอ)
   */
  proofPhotoUrls: string[];
}

/**
 * ผลลัพธ์การติดตามพัสดุในรูปแบบกลาง
 *
 * ⚠️ ทุกอย่างในนี้ยกเว้น `sensitive` ถูกเก็บลง tracking_cache ซึ่งเป็นของกลาง
 * ที่ทุกคนที่ค้นเลขเดียวกันใช้ร่วมกัน **ห้ามใส่อะไรที่ระบุตัวบุคคลลงในฟิลด์อื่น**
 * ชื่อคนที่จำเป็นต้องแสดงถูกปิดบังตั้งแต่ใน adapter แล้ว (ดู ShipmentDetails)
 */
export interface TrackingResult {
  /** เลขพัสดุที่ค้นหา (normalize แล้ว) */
  trackingNumber: string;
  /** ชื่อขนส่งภาษาไทย เช่น "ไปรษณีย์ไทย" */
  carrierName: string;
  /** รหัสขนส่งสำหรับใช้ในโค้ด เช่น "thailand-post" */
  carrierCode: string;
  status: TrackingStatus;
  /** ข้อความสถานะภาษาไทย (ใช้ของขนส่งถ้ามี ไม่งั้น fallback เป็น TRACKING_STATUS_TEXT) */
  statusText: string;
  /** เวลาอัปเดตล่าสุด ISO 8601 — null ถ้ายังไม่มีเหตุการณ์ใดเลย */
  lastUpdated: string | null;
  /** timeline เรียงจากเก่าไปใหม่ */
  events: TrackingEvent[];
  /**
   * รายละเอียดการจัดส่งเพิ่มเติม — null เมื่อขนส่งเจ้านั้นไม่ได้ส่งมา
   *
   * ฟิลด์นี้เพิ่มทีหลัง ข้อมูลเก่าใน cache จึงไม่มี ทุกที่ที่อ่านต้องรับ
   * undefined ได้ด้วย ไม่ใช่แค่ null
   */
  shipment?: ShipmentDetails | null;
  /**
   * ⚠️ ข้อมูลอ่อนไหว — **ถูกลบทิ้งก่อนเขียน cache เสมอ**
   *
   * มีค่าเฉพาะตอนที่เพิ่งยิงถาม API มาสดๆ เท่านั้น ผลที่อ่านจาก cache จะเป็น
   * null เสมอไม่ว่าคนอ่านจะมีสิทธิ์แค่ไหน (ดู rememberTracking ใน
   * lib/tracking-cache.ts) และ API route ต้องกรองอีกชั้นก่อนส่งออกไป
   */
  sensitive?: SensitiveDetails | null;
}

/** adapter ของขนส่งแต่ละเจ้าต้องมีหน้าตาแบบนี้ */
export interface CarrierAdapter {
  carrierCode: string;
  carrierName: string;
  track(trackingNumber: string): Promise<TrackingResult>;

  /**
   * ยิงซ้ำโดยระบุขนส่งเจาะจง สำหรับ adapter ที่ปกติตรวจจับขนส่งให้เอง
   *
   * มีไว้เพื่อกู้กรณีที่การตรวจจับอัตโนมัติเดาผิดจนตอบว่าไม่พบ ทั้งที่พัสดุมีอยู่จริง
   * adapter ที่ไม่ได้ตรวจจับเองไม่ต้องมีเมธอดนี้
   */
  trackWithCourier?(
    trackingNumber: string,
    courierCode: string,
  ): Promise<TrackingResult>;

  /**
   * เจ้านี้ตามเลขนี้ได้ไหม โดยยังไม่ต้องยิงจริง
   *
   * มีไว้ให้ผู้เรียกตัดสินลำดับการยิงล่วงหน้า สำหรับ adapter ที่บังคับให้ระบุ
   * ขนส่งเอง (เช่น ETrackings) การยิงเลขที่มันตามไม่ได้คือการทิ้งโควตาเปล่าๆ
   * แน่นอน adapter ที่ตามได้ทุกเลขไม่ต้องมีเมธอดนี้ (ถือว่าตามได้เสมอ)
   *
   * courierHint คือขนส่งที่ **ยืนยันแล้ว** ของเลขนี้ (เช่นจากผลที่เคยค้นสำเร็จ
   * มาก่อน) ไม่ใช่การเดา — เลขไทยจำนวนมากดู prefix แล้วบอกไม่ได้ว่าเป็นเจ้าไหน
   * (`TH…` ใช้ร่วมกันระหว่าง SPX กับ Flash) ค่านี้จึงเป็นทางเดียวที่ทำให้
   * adapter แบบระบุขนส่งใช้งานได้กับเลขส่วนใหญ่
   */
  canTrack?(trackingNumber: string, courierHint?: string): boolean;

  /**
   * รหัสขนส่งที่ควรลองระบุเจาะจงเมื่อการตรวจจับอัตโนมัติตอบว่าไม่พบ
   *
   * เรียงจากที่เจอปัญหาบ่อยที่สุดก่อน เพราะผู้เรียกจะลองตามลำดับและหยุดเมื่อครบ
   * เพดานที่กำหนดไว้ เพื่อไม่ให้เปลือง quota
   */
  retryCourierCodes?: readonly string[];
}

/**
 * ประเภทข้อผิดพลาดที่ adapter โยนออกมาได้
 * ตั้งใจให้เป็นชุดปิด เพื่อให้ API route map เป็น HTTP status ได้ครบทุกกรณี
 */
export type TrackingErrorCode =
  | "invalid_tracking_number"
  | "not_found"
  | "auth_failed"
  | "rate_limited"
  | "network_error"
  | "upstream_error"
  | "config_error"
  /**
   * เกินเพดานเวลารวมของคำขอ (ดู lib/request-deadline.ts)
   *
   * ต่างจาก network_error ตรงที่ **เราเป็นคนตัดเอง** ไม่ใช่ปลายทางเงียบ —
   * ต้องแยกให้ออกในสถิติ ไม่งั้นจะอ่านไม่ออกว่าตัวเลขที่เห็นคือขนส่งแย่ลง
   * หรือเพดานที่เราตั้งไว้สั้นเกินไป
   */
  | "timeout";

/**
 * error ที่ระบุสาเหตุได้ พร้อมข้อความไทยสำหรับโชว์ผู้ใช้
 *
 * ห้ามใส่ API key หรือ token ลงใน message เด็ดขาด เพราะ message ถูกส่งกลับไปหา client
 */
/**
 * ค่า upstreamCode ที่ทุก adapter ต้องติดไปกับ error ตอนยิงแล้วปลายทางไม่ตอบจนหมดเวลา
 *
 * มีเป็นค่าคงที่กลางเพราะมีคนอ่านค่านี้จริงสองที่ และทั้งสองที่ตัดสินใจต่างกัน
 * ถ้าเป็นแค่ string ลอยๆ:
 *   - gateway ของ Track123 ใช้ตัดสินว่า **ไม่ลองใหม่** (รอมา 20 วิแล้ว ลองอีกก็เกิน 40)
 *   - หน้าสถิติแอดมินใช้แยก "ปลายทางช้าจนหมดเวลา" ออกจาก "ต่อไม่ติด"
 *     ซึ่งเป็นคนละปัญหาและแก้คนละทาง
 */
export const TIMEOUT_UPSTREAM_CODE = "timeout";

export class CarrierError extends Error {
  readonly code: TrackingErrorCode;
  /** ข้อความภาษาไทยที่แสดงให้ผู้ใช้เห็นได้ */
  readonly userMessage: string;
  /**
   * code ดิบที่ระบบขนส่งตอบกลับมา เช่น "A0706" ของ Track123
   *
   * มีไว้ให้ log ฝั่งเซิร์ฟเวอร์อ้างถึงสาเหตุที่แท้จริงได้ตรงๆ โดยไม่ต้องไปแกะ
   * จาก debugMessage — ห้ามส่งค่านี้กลับไปหา client
   */
  readonly upstreamCode?: string;

  constructor(
    code: TrackingErrorCode,
    userMessage: string,
    options?: { cause?: unknown; debugMessage?: string; upstreamCode?: string },
  ) {
    super(options?.debugMessage ?? userMessage, { cause: options?.cause });
    this.name = "CarrierError";
    this.code = code;
    this.userMessage = userMessage;
    this.upstreamCode = options?.upstreamCode;
  }
}
