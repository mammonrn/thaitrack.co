/** ยาวสุดที่ยอมให้เขียนลง log — พอเห็นใจความ ไม่ทำให้ log แตก */
export const MAX_MESSAGE_LENGTH = 120;

/**
 * คำที่ถ้าโผล่มา แปลว่าท่อนนั้นอาจมีความลับ
 *
 * ตัดทั้งท่อนทิ้ง ไม่ใช่พยายามแยกว่าส่วนไหนคือค่า — การเดาขอบเขตของค่าผิด
 * แม้ครั้งเดียวคือความลับหลุดลง log ถาวร
 */
/**
 * ⚠️ ไม่มี \b ล้อมโดยตั้งใจ — ต้องจับ "apiKey", "access_token", "X-Api-Key"
 * ให้ได้ด้วย ไม่ใช่แค่คำโดดๆ · ผลข้างเคียงคือข้อความปกติที่บังเอิญมีคำพวกนี้
 * ก็ถูกตัดไปด้วย ซึ่งยอมรับได้: ตัดข้อความดีทิ้งเสียแค่ความสะดวกในการอ่าน log
 * แต่ปล่อยความลับหลุดคือความเสียหายถาวร
 */
const SECRET_WORDS =
  /(key|token|secret|password|passwd|authorization|bearer|credential|signature)/i;

/** ตัวเลข/ฐาน 16 ยาวๆ ที่มักเป็นคีย์หรือ id ภายใน */
const LONG_OPAQUE = /\b[A-Za-z0-9_-]{24,}\b/g;

/**
 * ทำให้ข้อความจากปลายทางปลอดภัยพอจะ log — คืน undefined เมื่อไม่มีอะไรให้เก็บ
 *
 * ทุกอย่างที่น่าสงสัยถูกแทนด้วย … ไม่ใช่พยายามเก็บให้ได้มากที่สุด
 */
export function safeUpstreamMessage(
  raw: string | null | undefined,
): string | undefined {
  const text = (raw ?? "").replace(/\s+/g, " ").trim();
  if (text === "") return undefined;

  const cleaned = text
    // ตัดท่อนที่มีคำบ่งชี้ความลับทิ้งทั้งท่อน (แยกด้วย , ; หรือ |)
    .split(/[,;|]/)
    .map((part) => (SECRET_WORDS.test(part) ? "…" : part))
    .join(",")
    // ค่ายาวๆ ที่ดูเป็นคีย์หรือ id ภายใน
    .replace(LONG_OPAQUE, "…")
    .trim();

  if (cleaned === "" || cleaned === "…") return undefined;

  return cleaned.length > MAX_MESSAGE_LENGTH
    ? `${cleaned.slice(0, MAX_MESSAGE_LENGTH)}…`
    : cleaned;
}
