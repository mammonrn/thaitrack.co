/**
 * เตรียมข้อความจากปลายทางให้ปลอดภัยพอจะเขียนลง log
 *
 * ══════════════════════════════════════════════════════════════════
 * ทำไมต้องเก็บ
 *
 * Track123 ตอบ A0706 กลับมาในสองบริบทที่พฤติกรรมต่างกันสิ้นเชิง:
 *
 *   auto-detect      โดน 3% · ลองใหม่แล้วสำเร็จ 29%
 *   ระบุ courier     โดน 60% · ลองใหม่แล้วสำเร็จ 2%
 *
 * เอกสารบอกว่า A0706 = "ยิงเกิน 5 ครั้ง/วินาที" แต่เราวัดแล้วว่ายิงสูงสุด
 * 3 ครั้ง/วินาที และตอนโดนปฏิเสธ 98% คิวว่างสนิท — ตัวเลขไม่เข้ากับคำอธิบาย
 *
 * เราเดามาแล้วสามรอบว่ามันแปลว่าอะไร (per-courier → per-endpoint → courier
 * ถูก/ผิด) และทุกรอบพังด้วยเหตุผลคนละอย่าง · ข้อความจริงจากปลายทางจะจบการเดา
 * ในบรรทัดเดียว
 *
 * ══════════════════════════════════════════════════════════════════
 * ⚠️ ข้อบังคับสี่ข้อ — ข้อความจากปลายทางคือข้อมูลที่เราไม่ได้ควบคุม
 *
 *   1. **ห้ามเข้าฐานข้อมูล** อยู่ใน pm2 log อย่างเดียว ซึ่ง rotate ทิ้งเอง
 *      (search_events มีข้อบังคับว่าห้ามมีเลขพัสดุ ดู 0007)
 *   2. **กรองความลับก่อนเสมอ** — ข้อความ error บางแบบมี key/token ติดมา
 *   3. **ตัดความยาว + บังคับให้เป็นบรรทัดเดียว** ปลายทางส่งอะไรมาก็ได้
 *      ไม่มีเพดาน และไม่มีอะไรห้ามมันส่ง newline หรือ \" มาด้วย
 *   4. **ห้ามเอาไปตัดสินใจในโค้ด** — รูปแบบเปลี่ยนเมื่อไรก็ได้ ใช้อ่านด้วยตา
 *      เท่านั้น (โค้ดตัดสินใจจาก upstreamCode ซึ่งเป็นชุดปิดที่มีเอกสารรองรับ)
 * ══════════════════════════════════════════════════════════════════
 */

/** ยาวสุดที่ยอมให้เขียนลง log — พอเห็นใจความ ไม่ทำให้ log แตก */
export const MAX_MESSAGE_LENGTH = 120;

/**
 * คำที่ถ้าโผล่มา แปลว่าท่อนนั้นอาจมีความลับ
 *
 * ตัดทั้งท่อนทิ้ง ไม่ใช่พยายามแยกว่าส่วนไหนคือค่า — การเดาขอบเขตของค่าผิด
 * แม้ครั้งเดียวคือความลับหลุดลง log ถาวร
 */
/**
 * ⚠️ ไม่มี \b ล้อมโดยตั้งใจ — ต้องจับ "apiKey", "access_token", "X-Api-Key"
 * ให้ได้ด้วย ไม่ใช่แค่คำโดดๆ · ผลข้างเคียงคือข้อความปกติที่บังเอิญมีคำพวกนี้
 * ก็ถูกตัดไปด้วย ซึ่งยอมรับได้: ตัดข้อความดีทิ้งเสียแค่ความสะดวกในการอ่าน log
 * แต่ปล่อยความลับหลุดคือความเสียหายถาวร
 */
const SECRET_WORDS =
  /(key|token|secret|password|passwd|authorization|bearer|credential|signature)/i;

/**
 * อักขระที่ทำให้บรรทัด log แตก หรือสั่งงาน terminal ได้
 *
 * ครอบคลุม C0/C1 ทั้งช่วง ไม่ใช่แค่ \n \r \t:
 *   - \u001B (ESC) เปิดลำดับสีของ terminal — ข้อความจากปลายทางต้องไม่มีสิทธิ์
 *     สั่งอะไรกับจอของคนที่ tail log อยู่
 *   - \u2028/\u2029 ขึ้นบรรทัดใหม่ในสายตาของเครื่องมือบางตัว
 *
 * ⚠️ ทำไมถึงสำคัญกว่าที่เห็น: ทั้ง grep และการนับทุกอย่างที่เราใช้วิเคราะห์
 * มาตลอด ตั้งอยู่บนสมมติฐานว่า "หนึ่งการเรียก = หนึ่งบรรทัด" ถ้าข้อความ
 * จากปลายทางแทรก newline ได้ บรรทัดจะแตกเป็นสองท่อน ท่อนหลังไม่มี prefix
 * [track123] แล้วตัวเลขทั้งหมดจะเพี้ยนแบบเงียบๆ โดยไม่มีอะไรผิดพลาดให้เห็น
 */
const LINE_BREAKERS = /[\u0000-\u001F\u007F-\u009F\u2028\u2029]/g;

/** ตัวเลข/ฐาน 16 ยาวๆ ที่มักเป็นคีย์หรือ id ภายใน */
const LONG_OPAQUE = /\b[A-Za-z0-9_-]{24,}\b/g;

/**
 * ทำให้ข้อความจากปลายทางปลอดภัยพอจะ log — คืน undefined เมื่อไม่มีอะไรให้เก็บ
 *
 * ทุกอย่างที่น่าสงสัยถูกแทนด้วย … ไม่ใช่พยายามเก็บให้ได้มากที่สุด
 */
export function safeUpstreamMessage(
  raw: string | null | undefined,
): string | undefined {
  const text = (raw ?? "")
    .replace(LINE_BREAKERS, " ")
    .replace(/\s+/g, " ")
    .trim();
  if (text === "") return undefined;

  const cleaned = text
    // ตัดท่อนที่มีคำบ่งชี้ความลับทิ้งทั้งท่อน (แยกด้วย , ; หรือ |)
    .split(/[,;|]/)
    .map((part) => (SECRET_WORDS.test(part) ? "…" : part))
    .join(",")
    // ค่ายาวๆ ที่ดูเป็นคีย์หรือ id ภายใน
    .replace(LONG_OPAQUE, "…")
    // เราห่อข้อความด้วย msg="…" ใน log — เครื่องหมายคำพูดข้างในจะปิดฟิลด์
    // ก่อนเวลาอันควร เปลี่ยนเป็น \' แทนการ escape เพราะ log บรรทัดนี้ไว้อ่าน
    // ด้วยตา ไม่ได้ไว้ parse — \\" ทำให้อ่านยากโดยไม่ได้อะไรเพิ่ม
    .replace(/"/g, "'")
    .trim();

  if (cleaned === "" || cleaned === "…") return undefined;

  return cleaned.length > MAX_MESSAGE_LENGTH
    ? `${cleaned.slice(0, MAX_MESSAGE_LENGTH)}…`
    : cleaned;
}
