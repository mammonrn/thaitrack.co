/* ------------------------------------------------------------------ *
 * ที่เก็บความจำ
 *
 * ใช้สองที่โดยตั้งใจ เพราะสองเรื่องนี้มีอายุไม่เท่ากัน:
 *
 *   sessionStorage  "ค้นสำเร็จแล้วในเซสชันนี้" — ต้องหายเมื่อปิดแท็บ ไม่งั้น
 *                   คนที่เคยค้นเมื่อเดือนที่แล้วจะโดนชวนตั้งแต่วินาทีแรกที่เปิดเว็บ
 *                   ทั้งที่ยังไม่ได้เห็นคุณค่าอะไรในครั้งนี้เลย
 *   localStorage    "กดปิดไปแล้ว" — **ต้องอยู่ข้ามเซสชัน**
 *
 * ทำไมการกดปิดต้องข้ามเซสชัน: กรณีที่เว็บตรวจไม่ได้ว่าติดตั้งไปแล้ว (ติดตั้งแล้ว
 * แต่กดลิงก์จากแชทจนเปิดในเบราว์เซอร์ปกติ — display-mode ตอนนั้นไม่ใช่ standalone)
 * การกดปิดคือสัญญาณเดียวที่เรามีว่า "ฉันมีแล้ว/ฉันไม่เอา" ถ้าจำแค่ในเซสชัน
 * คนกลุ่มนี้จะโดนชวนใหม่ทุกครั้งที่กดลิงก์ ตลอดไป
 *
 * เข้าถึงผ่านฟังก์ชันในไฟล์นี้เท่านั้น และกลืน error ทุกกรณี — Safari โหมดส่วนตัว
 * โยน error ตอนเขียน storage ซึ่งต้องไม่ทำให้หน้าเว็บพังเพราะเรื่องปุ่มชวนติดตั้ง
 * ------------------------------------------------------------------ */

const SEARCHED_KEY = "thaitrack.install-invite.searched";

/**
 * มี v1 ต่อท้ายโดยตั้งใจ
 *
 * "ปิดแล้วไม่กลับมาอีก" แปลว่าเราไม่มีทางชวนคนกลุ่มนี้ได้อีกเลย ถ้าวันหนึ่ง
 * แอพเปลี่ยนไปมากจนคุ้มที่จะถามใหม่ ทางที่ถูกคือขยับเป็น v2 ซึ่งเป็นการตัดสินใจ
 * ที่ต้องตั้งใจทำและเห็นได้ใน diff ไม่ใช่การแอบลดเวลาหมดอายุลงทีละนิด
 */
const DISMISSED_KEY = "thaitrack.install-invite.dismissed.v1";

/** event ที่หน้าค้นหายิงบอกปุ่มลอยว่า "ค้นสำเร็จแล้วนะ" */
export const SEARCH_SUCCESS_EVENT = "thaitrack:search-success";

/** อ่าน storage แบบไม่มีวันโยน error — null เมื่ออ่านไม่ได้ไม่ว่าด้วยเหตุใด */
function read(storage: "session" | "local", key: string): string | null {
  try {
    const store = storage === "session" ? sessionStorage : localStorage;
    return store.getItem(key);
  } catch {
    return null;
  }
}

/** เขียน storage แบบไม่มีวันโยน error */
function write(storage: "session" | "local", key: string, value: string): void {
  try {
    const store = storage === "session" ? sessionStorage : localStorage;
    store.setItem(key, value);
  } catch {
    // เขียนไม่ได้ = ปุ่มลอยจะทำงานเหมือนเซสชันใหม่เสมอ ซึ่งยอมรับได้
    // ดีกว่าทำให้หน้าเว็บล้มเพราะเรื่องปุ่มชวนติดตั้ง
  }
}

/** เคยค้นหาสำเร็จในเซสชันนี้หรือยัง */
export function hasSearchedThisSession(): boolean {
  return read("session", SEARCHED_KEY) === "1";
}

/**
 * บันทึกว่าเพิ่งค้นหาสำเร็จ แล้วบอกปุ่มลอยทันที
 *
 * ต้องยิง event เองเพราะ storage event ของเบราว์เซอร์ไม่ยิงให้แท็บที่เป็นคนเขียน
 * และปุ่มลอยอยู่คนละ component กับหน้าค้นหา (มันอยู่ใน layout เพื่อให้ติดตาม
 * ไปทุกหน้าหลังค้นเสร็จ)
 */
export function markSearchSuccess(): void {
  write("session", SEARCHED_KEY, "1");
  window.dispatchEvent(new Event(SEARCH_SUCCESS_EVENT));
}

/** เคยกดปิดปุ่มลอยไปแล้วหรือยัง (จำข้ามเซสชัน) */
export function wasDismissed(): boolean {
  return read("local", DISMISSED_KEY) !== null;
}

/**
 * คนที่รอฟังว่ามีการกดปิด
 *
 * มีเพราะค่านี้อยู่ใน localStorage ซึ่งเป็นสถานะของเบราว์เซอร์ ไม่ใช่ของ React
 * การให้ component subscribe ผ่าน useSyncExternalStore ทำให้ไม่ต้อง setState
 * ใน effect (ซึ่งทำให้เกิด render ซ้อน และ eslint ห้ามไว้ด้วยเหตุผลนั้น)
 *
 * storage event ของเบราว์เซอร์ใช้แทนไม่ได้ เพราะมันไม่ยิงให้แท็บที่เป็นคนเขียน
 */
const dismissalListeners = new Set<() => void>();

export function subscribeDismissal(onChange: () => void): () => void {
  dismissalListeners.add(onChange);
  return () => {
    dismissalListeners.delete(onChange);
  };
}

/** จำว่ากดปิดแล้ว — เก็บเวลาไว้ด้วยเผื่ออยากรู้ทีหลังว่าปิดไปนานแค่ไหน */
export function rememberDismissal(): void {
  write("local", DISMISSED_KEY, new Date().toISOString());
  for (const listener of dismissalListeners) listener();
}

/* ------------------------------------------------------------------ *
 * กติกาการแสดง
 * ------------------------------------------------------------------ */

export interface InviteConditions {
  /** สถานะการติดตั้งจาก useInstallState — ต้องเป็นสถานะที่กดแล้วมีอะไรเกิดขึ้นจริง */
  state: InstallState;
  /** ค้นหาสำเร็จแล้วอย่างน้อยหนึ่งครั้งในเซสชันนี้ */
  searched: boolean;
  /** เคยกดปิดไปแล้ว (จำข้ามเซสชัน) */
  dismissed: boolean;
  /** จอแคบพอที่ปุ่มลอยจะมีที่ยืน */
  narrow: boolean;
}

/**
 * ปุ่มลอยควรขึ้นไหม
 *
 * เงื่อนไขทั้งสี่ต้องจริงพร้อมกัน เรียงตามความสำคัญ:
 *
 *   1. สถานะต้องเป็น promptable หรือ manual เท่านั้น
 *      - installed   ติดตั้งไปแล้ว การชวนซ้ำคือการตื๊อคนที่ทำตามที่เราขอไปแล้ว
 *      - unsupported กดแล้วไม่มีอะไรเกิดขึ้น เป็นการหลอกให้กด
 *      - checking    ยังไม่รู้ว่าติดตั้งได้ไหม ขึ้นไปก่อนแล้วหายคือการกระพริบ
 *   2. ต้องค้นสำเร็จแล้ว — ชวนตอนที่เขาเพิ่งได้ประโยชน์จากเว็บไปหมาดๆ
 *      ไม่ใช่ตอนเพิ่งเปิดหน้าแรกที่ยังไม่รู้ว่าเว็บนี้ทำอะไรได้
 *   3. ต้องไม่เคยกดปิด — ปิดแล้วต้องหายจริง ไม่มีข้อยกเว้น ไม่มีวันหมดอายุ
 *   4. ต้องเป็นจอแคบ — บนเดสก์ท็อปมีปุ่ม "ดาวน์โหลด" อยู่บนหัวเว็บตลอดเวลา
 *      และ Chrome มีไอคอนติดตั้งบนแถบที่อยู่อยู่แล้ว ปุ่มลอยจึงเป็นการรบกวน
 *      ที่ไม่ได้เพิ่มทางเลือกอะไรให้เลย
 *
 * ⚠️ ห้ามเปลี่ยนข้อ 1 ให้รวม installed ไม่ว่าด้วยเหตุผลใด (มีเทสต์เฝ้าอยู่)
 */
export function shouldShowInvite(conditions: InviteConditions): boolean {
  const { state, searched, dismissed, narrow } = conditions;

  if (state !== "promptable" && state !== "manual") return false;
  if (!searched) return false;
  if (dismissed) return false;
  return narrow;
}

