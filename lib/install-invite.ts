/** สิ่งที่เกิดกับปุ่มลอยหนึ่งครั้ง */
export type InviteAction = "shown" | "dismissed" | "clicked";

/** นับ "แสดง" แค่ครั้งเดียวต่อเซสชัน ไม่งั้น conversion rate จะเพี้ยน */
const SHOWN_KEY = "thaitrack.install-invite.counted";

export function hasCountedShown(): boolean {
  return read("session", SHOWN_KEY) === "1";
}

export function markShownCounted(): void {
  write("session", SHOWN_KEY, "1");
}

/**
 * ส่งให้เซิร์ฟเวอร์นับ — ล้มเหลวได้เงียบๆ เหมือน reportInstall
 *
 * ใช้ endpoint เดียวกับการนับติดตั้ง (/api/installed) เพราะเป็นเรื่องเดียวกัน
 * คือ funnel ของการติดตั้ง และ endpoint นั้นมีกติกาความเป็นส่วนตัวเขียนไว้แล้ว
 * ว่าไม่เก็บอะไรที่ระบุตัวคน
 *
 * keepalive เพราะ "clicked" ตามมาด้วยหน้าต่างติดตั้งของเบราว์เซอร์ทันที
 * ซึ่งอาจทำให้ request ปกติถูกตัดกลางทาง
 */
export function reportInvite(action: InviteAction): Promise<void> {
  return fetch("/api/installed", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ action, platform: detectPlatform() }),
    keepalive: true,
  })
    .then(() => undefined)
    .catch(() => undefined);
}
