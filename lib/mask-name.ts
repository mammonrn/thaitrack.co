/**
 * ปิดบังชื่อคนบางส่วน — ให้เจ้าตัวจำได้ว่าใช่ตัวเอง แต่คนอื่นไม่ได้ชื่อเต็มไป
 *
 * ใช้กับชื่อผู้รับและผู้เซ็นรับ ซึ่งขนส่งบางเจ้าส่งมาแบบเต็มยศไม่ปิดบังอะไรเลย
 * (เจอจริง: "ภูมิ ธรรมสอน") การค้นหาในเว็บนี้ไม่ต้องพิสูจน์ตัวตน ใครก็ตามที่เห็น
 * เลขพัสดุบนกล่องหรือในกลุ่มแชทจึงจะได้ชื่อคนรับไปทันทีถ้าเราแสดงเต็ม
 *
 * ⚠️ ปิดบังตั้งแต่ตอนแปลงข้อมูลเข้าระบบ (ดู toShipmentDetails) ไม่ใช่ตอนแสดงผล
 * ค่าเต็มจึงไม่เคยออกจาก adapter ไปไหนเลย — ไม่ลง cache ไม่ลง response ไม่ลง log
 * นี่เป็นการรับประกันที่แข็งกว่าการกรองตอนขาออก เพราะไม่ต้องไปไล่อุดทุกทางที่
 * ข้อมูลไหลผ่าน และการเพิ่มทางใหม่ในอนาคตก็ปลอดภัยโดยอัตโนมัติ
 *
 * ทั้งไฟล์เป็นฟังก์ชันบริสุทธิ์
 */

/** ดาวที่ต่อท้ายส่วนที่ถูกปิด — จำนวนคงที่โดยตั้งใจ (ดูเหตุผลใน maskPersonName) */
const MASK = "***";

/** เก็บให้เห็นได้มากสุดกี่ตัวอักษรเมื่อชื่อมีคำเดียว */
const MAX_KEPT = 3;

/**
 * ตัดข้อความเป็น "ตัวอักษรที่คนมองเห็นเป็นตัวเดียว"
 *
 * จำเป็นสำหรับภาษาไทย เพราะสระบนล่างและวรรณยุกต์เป็นคนละ code point กับพยัญชนะ
 * ที่มันเกาะอยู่ การตัดด้วย slice() ตรงๆ จะได้สระลอยหรือพยัญชนะที่สระหายไป
 * เช่น "ภูมิ" มี 4 code point แต่คนเห็นเป็น 2 ตัว การเก็บ "2 ตัวแรก" ด้วย
 * slice(0,2) จะได้ "ภู" ซึ่งบังเอิญถูก แต่ "เมื่อ" จะได้ "เม" ที่ผิดรูป
 *
 * Intl.Segmenter มีใน Node 18+ และเบราว์เซอร์ปัจจุบันทั้งหมด แต่ยังกันพลาดไว้
 * ด้วย fallback ที่ตัดตาม code point เพราะฟังก์ชันนี้อยู่ในเส้นทางที่ห้ามพัง
 */
export function graphemes(text: string): string[] {
  if (typeof Intl.Segmenter === "function") {
    const segmenter = new Intl.Segmenter("th", { granularity: "grapheme" });
    return [...segmenter.segment(text)].map((entry) => entry.segment);
  }
  return [...text];
}

/**
 * ปิดบังชื่อคน — null เมื่อไม่มีอะไรให้แสดง
 *
 * กติกา:
 *
 *   หลายคำ  เก็บคำแรกไว้ทั้งคำ ที่เหลือเหลือตัวแรกของแต่ละคำ
 *           "ภูมิ ธรรมสอน"  → "ภูมิ ธ***"
 *           "John Smith"    → "John S***"
 *
 *   คำเดียว เก็บครึ่งแรกของชื่อ แต่ไม่เกิน 3 ตัวอักษร
 *           "แผนกต้อนรับ"   → "แผน***"
 *           "สมชาย"        → "สมช***"
 *           "สม"           → "ส***"
 *
 * ทำไมคำแรกถึงเก็บทั้งคำ: คนไทยเรียกกันด้วยชื่อต้น ถ้าปิดชื่อต้นด้วยจะไม่เหลือ
 * อะไรให้เจ้าของจำตัวเองได้ ซึ่งขัดกับเหตุผลที่แสดงมันตั้งแต่แรก ส่วนนามสกุลคือ
 * ส่วนที่ทำให้ตามตัวคนได้จริง จึงเป็นส่วนที่ต้องปิด
 *
 * ทำไมดาวถึงมีจำนวนคงที่ ไม่เท่าความยาวจริง: ความยาวของนามสกุลก็เป็นข้อมูลที่
 * ช่วยเดาได้ การใส่ดาวตามความยาวจริงจึงยังบอกอะไรออกไปโดยไม่จำเป็น และความกว้าง
 * ที่เท่ากันทุกแถวก็อ่านง่ายกว่าเมื่อวางเรียงกัน
 *
 * ชื่อสั้นมาก (1–2 ตัวอักษร) ยังเหลือตัวแรกให้เห็นเสมอ ไม่มีทางกลายเป็นดาวล้วน
 */
export function maskPersonName(raw: string | null | undefined): string | null {
  const value = (raw ?? "").trim().replace(/\s+/g, " ");
  if (value === "") return null;

  const words = value.split(" ");

  if (words.length > 1) {
    const rest = words
      .slice(1)
      .map((word) => `${graphemes(word)[0] ?? ""}${MASK}`)
      .join(" ");
    return `${words[0]} ${rest}`;
  }

  const letters = graphemes(value);
  const kept = Math.min(MAX_KEPT, Math.max(1, Math.ceil(letters.length / 2)));

  // ชื่อที่สั้นกว่าจำนวนที่จะเก็บอยู่แล้ว ไม่มีอะไรให้ปิด แต่ยังต่อดาวไว้เพื่อ
  // ไม่ให้ผู้ใช้เข้าใจว่านี่คือชื่อเต็มที่ขนส่งส่งมา
  return `${letters.slice(0, kept).join("")}${MASK}`;
}
