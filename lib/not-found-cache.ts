/**
 * cache ของคำตอบ "ไม่พบเลขนี้" — แยกจาก cache ของผลที่เจอโดยสิ้นเชิง
 *
 * ⚠️ **ห้ามเอาไปรวมกับ lib/cache.ts หรือตาราง tracking_cache เด็ดขาด** สองที่นั้น
 * เก็บ TrackingResult ที่เป็นคำตอบจริง มี TTL ตามสถานะพัสดุ และถูกใช้เป็น
 * "ของสำรอง" ตอนขนส่งล่ม ส่วนที่นี่เก็บแค่ "เคยถามแล้วไม่มีใครรู้จักเลขนี้"
 * ซึ่งไม่ใช่คำตอบและใช้เป็นของสำรองไม่ได้ การเอามาปนกันจะทำให้ไม่มีทางแยกได้ว่า
 * แถวไหนคือของจริงแถวไหนคือความว่างเปล่า
 *
 * ── ทำไมต้องมี ────────────────────────────────────────────────────────
 * จาก search_events 14 วัน: การค้นที่ได้ not_found 113 ครั้ง มี 37 ครั้ง (32%)
 * เป็นการค้น **เลขเดิมซ้ำ** (TH300993YZCY4 ×7, 260901UGNTF91S ×6,
 * SHNT072462018B ×5) ทุกครั้งวิ่งครบทั้งสายผู้ให้บริการ = ราว 185 การยิงเปล่า
 * และผู้ใช้รอ p50 5.4 วินาที เพื่อให้ได้คำตอบเดิมที่เราเพิ่งรู้เมื่อกี้
 *
 * ── ทำไม TTL แค่ 10 นาที ─────────────────────────────────────────────
 * เลขที่ยังไม่ขึ้นระบบขนส่งจะขึ้นภายใน 1–2 ชั่วโมง (ข้อความบนการ์ดก็บอกแบบนั้น)
 * ถ้าเก็บนานกว่านี้ คนที่รอเลขขึ้นระบบแล้วกดเช็คซ้ำจะเจอ "ไม่พบ" ค้างอยู่ทั้งที่
 * พัสดุขึ้นระบบไปแล้ว — ความเสียหายของการตอบผิดหนักกว่าค่ายิงที่ประหยัดได้
 * 10 นาทีกินการกดซ้ำรัวๆ ในรอบเดียวกันได้หมด ซึ่งเป็นพฤติกรรมที่เห็นในสถิติจริง
 *
 * ── ทำไมไม่มีชั้นถาวร ────────────────────────────────────────────────
 * ชั้นถาวรมีไว้สองเรื่อง: รอด restart และแชร์ข้าม instance · เรื่องแรกไม่สำคัญ
 * เพราะ TTL สั้นกว่าระยะห่างของการ deploy อยู่แล้ว เรื่องที่สองไม่มีอยู่จริง
 * เพราะรันอยู่ instance เดียวใต้ pm2 · การเขียน Supabase ทุกครั้งที่ค้นไม่เจอ
 * จึงเป็นต้นทุนล้วนๆ ที่ไม่ได้อะไรกลับมา
 */

/** อายุของคำตอบ "ไม่พบ" — ดูเหตุผลของตัวเลขนี้ที่หัวไฟล์ */
export const NOT_FOUND_TTL_MS = 10 * 60_000;

/**
 * เพดานจำนวนรายการ — เล็กกว่า cache ของผลที่เจอมาก เพราะอายุสั้นกว่า 4,000 เท่า
 * (10 นาที เทียบกับ 30 วันของ delivered) จำนวนที่มีชีวิตอยู่พร้อมกันจึงน้อยกว่ามาก
 */
const MAX_ENTRIES = 2_000;

export interface NotFoundEntry {
  /** เวลาที่ได้คำตอบ "ไม่พบ" มาจากขนส่งจริง (epoch ms) */
  recordedAt: number;
  /** เวลาหมดอายุ (epoch ms) */
  expiresAt: number;
}

/** key = เลขพัสดุที่ normalize แล้ว */
const store = new Map<string, NotFoundEntry>();

/**
 * จำว่าเลขนี้ถามแล้วไม่เจอ
 *
 * เขียนทับของเดิมเสมอ (ไม่ใช่ต่ออายุของเดิม) เพราะแต่ละครั้งคือการยืนยันใหม่
 * จากขนส่งจริง ณ เวลานั้น
 */
export function rememberNotFound(
  trackingNumber: string,
  now: number = Date.now(),
): NotFoundEntry {
  // ลบก่อนใส่ เพื่อให้ Map เรียงตามลำดับการเขียนล่าสุดจริงๆ ไม่งั้นการเขียนทับ
  // key เดิมจะไม่ขยับตำแหน่ง แล้วการกวาดข้างล่างจะทิ้งของที่เพิ่งเขียนไป
  store.delete(trackingNumber);

  const entry: NotFoundEntry = {
    recordedAt: now,
    expiresAt: now + NOT_FOUND_TTL_MS,
  };
  store.set(trackingNumber, entry);

  // เต็มแล้วทิ้งของที่เก่าที่สุด — Map ของ JS เรียงตามลำดับการใส่ ตัวแรกที่วนเจอ
  // จึงเป็นตัวที่เก่าที่สุดเสมอ
  while (store.size > MAX_ENTRIES) {
    const oldest = store.keys().next();
    if (oldest.done === true) break;
    store.delete(oldest.value);
  }

  return entry;
}

/**
 * เคยถามเลขนี้แล้วไม่เจอ และคำตอบนั้นยังไม่หมดอายุหรือเปล่า
 *
 * คืน null เมื่อไม่เคยถาม หรือถามแล้วแต่เกิน TTL ไปแล้ว — ทั้งสองกรณีแปลว่า
 * "ต้องไปถามขนส่งใหม่" เหมือนกัน ผู้เรียกจึงไม่ต้องแยกสองกรณีนี้
 *
 * ของหมดอายุถูกลบทิ้งทันทีที่อ่านเจอ ต่างจาก cache ของผลที่เจอซึ่งเก็บของเก่าไว้
 * เป็นคำตอบสำรอง — "ไม่พบเมื่อ 20 นาทีที่แล้ว" ไม่มีค่าเป็นคำตอบสำรองของอะไรเลย
 */
export function lookupNotFound(
  trackingNumber: string,
  now: number = Date.now(),
): NotFoundEntry | null {
  const entry = store.get(trackingNumber);
  if (entry === undefined) return null;

  if (now >= entry.expiresAt) {
    store.delete(trackingNumber);
    return null;
  }

  return entry;
}

/** ล้างทั้งหมด — มีไว้ให้เทสต์เริ่มจากศูนย์ทุกครั้ง ไม่ได้เรียกจากโค้ดจริง */
export function clearNotFoundCache(): void {
  store.clear();
}

/** จำนวนรายการที่เก็บอยู่ (รวมของที่หมดอายุแต่ยังไม่ถูกอ่านเจอ) — ใช้ในเทสต์ */
export function notFoundCacheSize(): number {
  return store.size;
}
