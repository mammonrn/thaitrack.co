/**
 * ใครมีสิทธิ์เห็นรูปถ่ายตอนนำจ่าย
 *
 * รูปนี้ถ่ายที่หน้าบ้านผู้รับ และมักติดใบปะหน้าที่มีที่อยู่เต็มมาด้วย มันจึงเป็น
 * ข้อมูลที่อ่อนไหวที่สุดที่ระบบนี้แตะ — อ่อนไหวกว่าชื่อผู้รับเสียอีก
 *
 * เกณฑ์: **ล็อกอินอยู่ และบันทึกพัสดุเลขนี้ไว้ก่อนที่มันจะถึงมือผู้รับ**
 *
 * เหตุผลของข้อหลังคือสิ่งที่ทำให้เกณฑ์นี้มีความหมาย — คนที่ตามพัสดุตั้งแต่ยัง
 * ไม่ถึงมีแนวโน้มเป็นเจ้าของจริง (เขารู้เลขตั้งแต่ตอนสั่งของ) ต่างจากคนที่หยิบ
 * เลขจากกล่องที่ทิ้งแล้วมาค้นย้อนหลัง ซึ่งใครก็ทำได้ เวลาที่บันทึกจึงเป็น
 * หลักฐานอ่อนๆ ของความเป็นเจ้าของที่ปลอมย้อนหลังไม่ได้
 *
 * ⚠️ ไม่ใช่การพิสูจน์ตัวตนจริง คนที่ได้เลขมาก่อนของถึงก็ผ่านเกณฑ์นี้ได้ แต่มัน
 * ตัดกรณีที่ง่ายที่สุดและน่ากลัวที่สุดออกไป (เอาเลขจากกล่องมาส่องรูปบ้านคนอื่น)
 * โดยไม่ต้องบังคับให้ผู้ใช้ยืนยันตัวตนอะไรเพิ่ม
 *
 * ทั้งไฟล์เป็นฟังก์ชันบริสุทธิ์ ให้ผู้เรียกไปหาข้อมูลมาเอง
 */

import type { TrackingStatus } from "./carriers/types";

export interface ProofAccessInput {
  status: TrackingStatus;
  /** เวลาอัปเดตล่าสุดของพัสดุ (ISO 8601) — ใช้เป็นเวลาที่ถึงมือผู้รับ */
  lastUpdated: string | null;
  /** เวลาที่ผู้ใช้คนนี้กดบันทึกเลขนี้ไว้ (ISO 8601) — null คือไม่เคยบันทึก */
  savedAt: string | null;
}

/**
 * มีสิทธิ์เห็นรูปไหม
 *
 * ใช้ "เวลาอัปเดตล่าสุด" เป็นเวลาที่ถึงมือผู้รับ เพราะพัสดุที่สถานะเป็นส่งถึงแล้ว
 * เหตุการณ์ล่าสุดของมันคือการนำจ่ายแทบทุกครั้ง ถ้ามีเหตุการณ์อื่นตามมาทีหลัง
 * เกณฑ์จะเข้มขึ้น (ต้องบันทึกก่อนเหตุการณ์นั้น) ซึ่งพลาดไปทางที่ปลอดภัย
 *
 * ทุกกรณีที่ข้อมูลไม่ครบตอบ false เสมอ — fail closed
 */
export function canRevealProof(input: ProofAccessInput): boolean {
  if (input.status !== "delivered") return false;
  if (input.savedAt === null || input.lastUpdated === null) return false;

  const deliveredAt = Date.parse(input.lastUpdated);
  const savedAt = Date.parse(input.savedAt);

  if (!Number.isFinite(deliveredAt) || !Number.isFinite(savedAt)) return false;

  return savedAt < deliveredAt;
}
