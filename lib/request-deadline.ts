/**
 * เพดานเวลาของ "หนึ่งคำขอ" ไม่ใช่ของการยิงแต่ละครั้ง
 *
 * ── ปัญหาที่แก้ ───────────────────────────────────────────────────────
 * timeout เดิมทั้งหมดเป็นแบบต่อการยิงหนึ่งครั้ง (Track123 10 วิ, ไปรษณีย์ไทย
 * มีของตัวเอง) แต่หนึ่งคำขอของผู้ใช้ยิงได้ถึง 5 ครั้ง บวกเวลารอคิว บวก backoff
 * ตอนโดน A0706 เวลารวมจึงไม่มีเพดานอะไรกั้นเลย จาก search_events 14 วัน:
 * การค้นที่ตอบว่าไม่พบใช้เวลา p95 12,536 ms และมีที่แตะ 14 วินาที
 *
 * ── ทำไม 10 วินาที ───────────────────────────────────────────────────
 * จากข้อมูลจริงชุดเดียวกัน การค้นที่ **เจอ** ใช้เวลาสูงสุด 9,802 ms · เพดาน
 * 10 วินาทีจึงไม่ตัดคำขอที่กำลังจะสำเร็จแม้แต่รายการเดียวเท่าที่มีข้อมูล ส่วน
 * 8 วินาทีที่เคยคิดไว้จะตัดของจริงทิ้ง เลขนี้ต้องทบทวนใหม่เมื่อมีข้อมูลมากขึ้น
 * — ถ้าเห็น timeout ในหน้าสถิติพร้อมกับยอด "เจอ" ที่ลดลง แปลว่าตัดสั้นเกินไป
 *
 * ── กันสองชั้น ──────────────────────────────────────────────────────
 *   1. ชั้นร่วมมือ (expired) — ไม่ **เริ่ม** การยิงครั้งใหม่เมื่อเวลาหมดแล้ว
 *      ชั้นนี้ประหยัดโควตาจริง เพราะการยิงที่เริ่มตอนเหลือเวลา 200 ms คือการ
 *      จ่ายเงินซื้อคำตอบที่ไม่มีทางได้ใช้
 *   2. ชั้นบังคับ (race) — คืนคำตอบที่ 10 วินาทีเสมอ ต่อให้การยิงที่ค้างอยู่
 *      ไม่ยอมจบ ชั้นนี้คือสิ่งที่ผู้ใช้รู้สึกได้จริง
 *
 * ⚠️ การยิงที่ค้างอยู่ **ไม่ได้ถูกยกเลิก** ตอนชั้นที่สองตัด — มันวิ่งต่อจนจบแล้ว
 * เขียนผลลง cache ตามปกติ ซึ่งเป็นสิ่งที่ต้องการ: คนที่กดค้นซ้ำอีกสิบวินาที
 * ถัดมาจะได้ของจาก cache ทันที ไม่ใช่ไปเริ่มยิงใหม่ทั้งชุด
 */

import { CarrierError } from "./carriers/types";

/**
 * เพดานเวลารวมต่อหนึ่งคำขอค้นหา (ms) — ดูที่มาของตัวเลขที่หัวไฟล์
 *
 * export ไว้ให้เทสต์อ้างถึงได้ จะได้ไม่มีเลข 10000 ลอยอยู่สองที่แล้วเพี้ยนจากกัน
 */
export const REQUEST_BUDGET_MS = 10_000;

/** error ที่แปลว่า "หมดเวลาที่เราให้ ไม่ใช่ปลายทางตอบว่าไม่มี" */
export function deadlineError(elapsedMs: number): CarrierError {
  return new CarrierError(
    "timeout",
    "ระบบขนส่งตอบช้ากว่าปกติ ยังไม่ได้ข้อมูลในเวลาที่กำหนด ลองกดค้นหาอีกครั้ง",
    {
      debugMessage: `เกินเพดาน ${REQUEST_BUDGET_MS} ms (ใช้ไป ${elapsedMs} ms)`,
      upstreamCode: "deadline_exceeded",
    },
  );
}

/**
 * นาฬิกาจับเวลาของหนึ่งคำขอ — สร้างครั้งเดียวตอนคำขอเข้ามา แล้วส่งต่อลงไป
 *
 * ตั้งใจไม่ใช้ AbortSignal.timeout() เพราะสิ่งที่ต้องการคือ "ถามได้ว่าเหลือ
 * เวลาเท่าไร" ที่จุดตัดสินใจหลายจุด ไม่ใช่แค่สัญญาณยกเลิกครั้งเดียว และเพราะ
 * เราตั้งใจ **ไม่** ยกเลิกการยิงที่ค้างอยู่ (ดูเหตุผลที่หัวไฟล์)
 */
export class Deadline {
  readonly budgetMs: number;
  private readonly startedAt: number;

  constructor(budgetMs: number = REQUEST_BUDGET_MS, now: number = Date.now()) {
    this.budgetMs = budgetMs;
    this.startedAt = now;
  }

  /** ใช้เวลาไปแล้วกี่ ms */
  elapsed(now: number = Date.now()): number {
    return now - this.startedAt;
  }

  /** เหลือเวลาอีกกี่ ms — ไม่ต่ำกว่า 0 */
  remaining(now: number = Date.now()): number {
    return Math.max(0, this.budgetMs - this.elapsed(now));
  }

  /** หมดเวลาแล้วหรือยัง — จุดตัดสินใจว่าจะ "เริ่ม" ยิงครั้งต่อไปไหม */
  expired(now: number = Date.now()): boolean {
    return this.remaining(now) === 0;
  }

  /**
   * รอผลจนกว่าจะเสร็จ หรือจนหมดเวลา — อย่างใดมาก่อน
   *
   * งานที่ยังไม่เสร็จถูกปล่อยให้วิ่งต่อ ไม่ได้ยกเลิก · ต้องผูก catch ทิ้งไว้ให้
   * ด้วย ไม่งั้นถ้ามันล้มทีหลังจะกลายเป็น unhandled rejection ที่ทำให้โปรเซส
   * ตายทั้งตัวใน Node รุ่นใหม่ — ผู้เรียกเดินหน้าไปแล้วจึงไม่มีใครรับ error นั้น
   */
  async race<T>(work: Promise<T>): Promise<T> {
    let timer: NodeJS.Timeout | undefined;

    const cutoff = new Promise<never>((_, reject) => {
      timer = setTimeout(() => {
        reject(deadlineError(this.elapsed()));
      }, this.remaining());
    });

    // ⚠️ ตั้งใจไม่ unref() timer ตัวนี้ · เคยลองแล้วพัง: test runner ของ Node
    // ถือว่า "event loop ว่างแล้วแต่ยังมี promise ค้าง" เป็นความผิดพลาด แล้ว
    // ยกเลิกเทสต์ทิ้งทั้งไฟล์ · ไม่ต้องกลัวว่ามันจะกันโปรเซสไม่ให้ปิด เพราะ
    // finally ข้างล่างเคลียร์ทุกทางออก ทั้งขาที่งานเสร็จทันและขาที่ถูกตัด

    work.catch(() => {
      /* ผู้เรียกอาจเดินหน้าไปแล้ว — กลืนไว้เพื่อไม่ให้เป็น unhandled rejection */
    });

    try {
      return await Promise.race([work, cutoff]);
    } finally {
      if (timer !== undefined) clearTimeout(timer);
    }
  }
}
