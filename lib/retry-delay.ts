/**
 * เวลารอก่อนกดปุ่ม "ลองอีกครั้ง" ได้ — ตรรกะล้วน แยกไว้ให้เทสต์ครอบ
 *
 * ══════════════════════════════════════════════════════════════════
 * ทำไมต้องมีการรอเลย
 *
 * upstream_error เกิดตอนปลายทางตอบไม่ทัน (Track123 ตัดที่ ~6 วินาที) ซึ่งเป็น
 * อาการชั่วคราวที่มักหายเอง · แต่ถ้าให้กดได้ทันที คนจะกดรัวสามครั้งใน 30 วินาที
 * แล้วล้มทั้งสามครั้ง — ของจริงที่เจอในสถิติ — แล้วเลิกไปเลย
 *
 * การรอจึงไม่ใช่การกันผู้ใช้ แต่เป็นการเพิ่มโอกาสที่การกดครั้งถัดไปจะสำเร็จ
 *
 * ══════════════════════════════════════════════════════════════════
 * ⚠️ backoff นี้ **ผู้ใช้เห็น** ไม่ใช่ที่ซ่อนไว้
 *
 * ปุ่มขึ้นตัวเลขนับถอยหลังให้เห็น — ปุ่มที่กดไม่ได้เฉยๆ โดยไม่บอกเหตุผล
 * อ่านแล้วเหมือนเว็บค้าง ซึ่งแย่กว่าการรอที่รู้ว่ากำลังรออะไร
 */

/**
 * รอกี่วินาทีสำหรับการกดครั้งแรก
 *
 * ⚠️ 10 ไม่ใช่ตัวเลขที่พิสูจน์แล้ว — จาก log มีเคสที่ลองใหม่ใน 7 วินาทีแล้ว
 * สำเร็จ แต่นั่นเป็นตัวอย่างเดียว จึงเผื่อขึ้นมาเป็น 10
 *
 * ต้องกลับมาปรับเมื่อมีข้อมูลจากตัวนับจริง (retried / retried+found ในหน้าสถิติ)
 */
export const FIRST_RETRY_SECONDS = 10;

/** เพดานการรอ — นานกว่านี้คนไม่รออยู่แล้ว การขึ้นเลขใหญ่มีแต่ทำให้เลิก */
export const MAX_RETRY_SECONDS = 40;

/**
 * กดไปแล้ว n ครั้ง → ครั้งถัดไปต้องรอกี่วินาที
 *
 * คูณสองไปเรื่อยๆ จนชนเพดาน: 10 → 20 → 40 → 40 …
 *
 * เพิ่มขึ้นเพราะ "กดแล้วยังล้ม" เป็นสัญญาณว่าปลายทางยังไม่ฟื้น การกดถี่ขึ้น
 * ในสถานการณ์นั้นมีแต่จะซ้ำเติมทั้งเราและเขา
 */
export function retryDelaySeconds(attemptsAlreadyMade: number): number {
  const doubled = FIRST_RETRY_SECONDS * 2 ** Math.max(0, attemptsAlreadyMade);
  return Math.min(doubled, MAX_RETRY_SECONDS);
}
