/**
 * กติกาว่า "เปิดหน้าประวัติแล้วต้องยิงถามพัสดุใบไหนใหม่บ้าง"
 *
 * ปัญหาที่แก้: หน้าประวัติแสดง snapshot ที่ถูกเขียนไว้ตอนกดบันทึก แล้วไม่มี
 * อะไรอัปเดตมันอีกเลย ผู้ใช้จึงเห็น "อยู่ระหว่างขนส่ง" ค้างอยู่ทั้งที่พัสดุ
 * ส่งถึงไปตั้งแต่เมื่อวาน — ต้องกดเข้าไปดูรายตัวถึงจะเห็นของจริง
 *
 * ------------------------------------------------------------------
 * ทำไมถึงไม่รีเฟรชทุกใบ
 *
 * พัสดุที่ถึงปลายทางแล้วไม่มีทางเปลี่ยนสถานะอีก การยิงถามซ้ำได้คำตอบเดิมเป๊ะๆ
 * เสมอ (นี่คือเหตุผลเดียวกับที่ TTL ของ delivered ยาว 30 วัน — ดู lib/cache.ts)
 * แถวพวกนั้นจึงใช้ค่าที่บันทึกไว้ได้เลย
 *
 * ⚠️ exception ("พัสดุมีปัญหา") **ไม่ใช่** สถานะจบ และเป็นแถวที่ต้องรีเฟรช
 * มากที่สุดด้วยซ้ำ — มันรวม "นำจ่ายไม่สำเร็จ" ที่ขนส่งมักกลับมาส่งใหม่ในวันถัดไป
 * การเหมาว่าจบแล้วจะทำให้ผู้ใช้เห็นว่าพัสดุมีปัญหาค้างอยู่ ทั้งที่ส่งสำเร็จไป
 * ตั้งแต่เช้า ซึ่งคืออาการเดียวกับบั๊กที่ไฟล์นี้ตั้งใจแก้
 * ------------------------------------------------------------------
 */

import type { TrackingStatus } from "./carriers/types";

/**
 * สถานะที่ถือว่า "จบแล้ว" — ไม่ต้องยิงถามซ้ำ
 *
 * มีตัวเดียวโดยตั้งใจ ระบบนี้ไม่มีสถานะ "ยกเลิก" แยกต่างหาก (ดู TrackingStatus
 * ใน lib/carriers/types.ts) พัสดุที่ถูกตีกลับ/ยกเลิกจะมาเป็น exception ซึ่ง
 * ยังเปลี่ยนต่อได้ จึงไม่นับเป็นสถานะจบ
 *
 * ⚠️ ก่อนเพิ่มค่าใหม่เข้าชุดนี้ ให้ถามคำถามเดียว: "ค่านี้เปลี่ยนเป็นอย่างอื่น
 * ได้อีกไหม" ถ้าตอบว่าได้แม้แต่กรณีเดียว มันไม่ใช่สถานะจบ และการใส่เข้ามาจะ
 * ทำให้สถานะค้างแบบเงียบๆ ซึ่งไม่มี error ที่ไหนขึ้นเลย
 */
export const TERMINAL_STATUSES: ReadonlySet<TrackingStatus> = new Set([
  "delivered",
]);

/** แถวนี้ต้องยิงถามใหม่ไหม */
export function needsStatusRefresh(row: {
  lastStatus: TrackingStatus | null;
}): boolean {
  // null = ยังไม่เคยมีสถานะ (บันทึกไว้ก่อนขนส่งรับเข้าระบบ) ต้องถามใหม่แน่นอน
  if (row.lastStatus === null) return true;
  return !TERMINAL_STATUSES.has(row.lastStatus);
}

/** คัดเฉพาะแถวที่ต้องรีเฟรช — ลำดับเดิมไม่เปลี่ยน */
export function pickForRefresh<T extends { lastStatus: TrackingStatus | null }>(
  items: readonly T[],
): T[] {
  return items.filter(needsStatusRefresh);
}

/**
 * ยิงพร้อมกันได้กี่ใบ
 *
 * ------------------------------------------------------------------
 * ทำไมถึงเป็น "จำกัดความพร้อมกัน" ไม่ใช่ "จำกัดจำนวนใบต่อการเปิดหน้า"
 *
 * ถ้าตัดจำนวนใบทิ้ง (เช่นรีเฟรชแค่ 10 ใบแรกจาก 19 ใบ) ใบที่เหลือก็ยังโชว์
 * สถานะค้างอยู่ดี — ซึ่งคือบั๊กที่กำลังแก้ แค่เกิดกับพัสดุน้อยใบลง
 *
 * และการตัดทิ้งไม่ได้ประหยัดโควตาของเจ้าหลักจริง เพราะ **Track123 คิดโควตาเป็น
 * จำนวนเลขพัสดุต่อรอบบิล ไม่ใช่จำนวน request** (ดู lib/provider-usage.ts)
 * เลขที่ผู้ใช้บันทึกไว้ถูกนับไปแล้วตั้งแต่ตอนกดบันทึก การถามซ้ำในรอบบิลเดียวกัน
 * จึงไม่เพิ่มยอดบิล ของที่ต้องกันจริงคือ **การยิงพรวดเดียวหลายสิบ request**
 * ซึ่งชนเพดาน 5 req/s ของ Track123 การหรี่ให้ไหลทีละน้อยแก้ตรงจุดนั้นพอดี
 *
 * ด่านที่ช่วยอีกชั้นคือ cache สองชั้นเดิม — ใบที่ยังไม่หมดอายุตอบจาก cache
 * โดยไม่ยิงใครเลย (in_transit เก็บ 2 ชม. · out_for_delivery 15 นาที)
 * ผู้ใช้ที่เปิดหน้าประวัติซ้ำในช่วงนั้นจึงไม่เสียอะไรเพิ่มเลยสักครั้ง
 * ------------------------------------------------------------------
 */
export const REFRESH_CONCURRENCY = 4;

/**
 * ทำทีละ limit ตัวจนครบ แล้วคืนผลตามลำดับเดิม
 *
 * ตัวที่ throw ไม่ทำให้ทั้งชุดล้ม — ผู้เรียกได้ null ตรงตำแหน่งนั้นแทน เพราะ
 * การรีเฟรชเป็นของเสริม พัสดุใบเดียวที่ขนส่งตอบไม่ได้ต้องไม่ทำให้ทั้งหน้าพัง
 */
export async function mapWithConcurrency<T, R>(
  items: readonly T[],
  limit: number,
  run: (item: T) => Promise<R>,
): Promise<(R | null)[]> {
  const results: (R | null)[] = new Array(items.length).fill(null);
  let next = 0;

  const worker = async (): Promise<void> => {
    for (;;) {
      const index = next;
      next += 1;
      if (index >= items.length) return;

      try {
        results[index] = await run(items[index]);
      } catch {
        // ปล่อยเป็น null — ผู้เรียกแปลว่า "ใบนี้รีเฟรชไม่ได้ ใช้ค่าเดิมไปก่อน"
        results[index] = null;
      }
    }
  };

  const size = Math.max(1, Math.min(limit, items.length));
  await Promise.all(Array.from({ length: size }, worker));

  return results;
}
