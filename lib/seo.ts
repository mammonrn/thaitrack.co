/**
 * เครื่องมือจัดข้อความ meta ให้อยู่ในความยาวที่ใช้ได้จริง
 *
 * ------------------------------------------------------------------
 * ทำไมต้องมีตัวช่วย ไม่ใช่เขียนสตริงตรงๆ
 *
 * เว็บนี้สร้างหน้ามากกว่าพันหน้าจากข้อมูลชุดเดียว ความยาวของ title กับ
 * description จึงเปลี่ยนไปตามชื่อจังหวัด/อำเภอที่ยาวไม่เท่ากัน — เขียน
 * template ครั้งเดียวแล้วปล่อยไปจะได้ทั้งหน้าที่สั้นเกินและยาวเกินปนกัน
 * โดยไม่มีใครรู้ เพราะไม่มีใครเปิดดูครบพันหน้า
 *
 * เกณฑ์ที่ใช้:
 *   title       ไม่เกิน 60 ตัวอักษร — ยาวกว่านี้ Google ตัดกลางคำ
 *   description 120-155 ตัวอักษร — สั้นกว่านี้ Google มักเขียนใหม่เอง
 *               โดยดึงข้อความจากหน้ามาแทน ซึ่งควบคุมไม่ได้
 *
 * นับเป็น "ตัวอักษร" ด้วย [...text] ไม่ใช่ .length เพราะภาษาไทยมีสระและ
 * วรรณยุกต์ที่เป็น code unit แยก การนับผิดจะทำให้ตัดข้อความผิดตำแหน่ง
 * ------------------------------------------------------------------
 */

/** ชื่อเว็บที่ต่อท้าย title เมื่อยังมีที่เหลือพอ */
export const SITE_SUFFIX = " — พัสดุไทย.com";

export const TITLE_MAX = 60;
export const DESCRIPTION_MIN = 120;
export const DESCRIPTION_MAX = 155;

/** จำนวนตัวอักษรจริง (ไม่ใช่ code unit) */
export function textLength(value: string): number {
  return [...value].length;
}

/**
 * ต่อชื่อเว็บท้าย title ถ้ายังไม่เกินเพดาน
 *
 * ชื่อเว็บมีค่าใน SERP (คนจำแบรนด์ได้) แต่มีค่าน้อยกว่าคำที่บอกว่าหน้านี้คือ
 * อะไร — เมื่อที่ไม่พอ จึงตัดชื่อเว็บทิ้งก่อนเสมอ ไม่ใช่ตัดเนื้อหา
 */
export function fitTitle(core: string): string {
  const withSuffix = `${core}${SITE_SUFFIX}`;
  return textLength(withSuffix) <= TITLE_MAX ? withSuffix : core;
}

/**
 * ประกอบ description จากประโยคหลัก + ส่วนขยายที่ใส่เพิ่มได้ถ้ายังมีที่เหลือ
 *
 * ใส่ทีละชิ้นแล้วหยุดเมื่อจะเกินเพดาน — ผลคือหน้าที่ชื่อสั้นได้รายละเอียด
 * มากกว่าหน้าที่ชื่อยาว โดยไม่มีหน้าไหนถูกตัดกลางคำ
 *
 * ⚠️ ส่วนขยายต้องเป็นข้อมูล **เฉพาะของหน้านั้น** (ชื่อตำบล จำนวนรหัส) ไม่ใช่
 * ประโยคโฆษณาที่เหมือนกันทุกหน้า — ถ้าทุกหน้าลงท้ายเหมือนกันหมด Google จะ
 * มองว่าเป็นเนื้อหาซ้ำ ซึ่งแย่กว่าการมี description สั้น
 */
export function fitDescription(base: string, extras: readonly string[]): string {
  let text = base;

  for (const extra of extras) {
    const next = `${text} ${extra}`;
    if (textLength(next) > DESCRIPTION_MAX) break;
    text = next;
  }

  return text;
}
