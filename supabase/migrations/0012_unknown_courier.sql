alter table public.search_events
  add column if not exists unknown_courier boolean not null default false;

/*
 * จำนวนคำขอที่ล้มเพราะเหลือผู้ให้บริการเจ้าเดียว
 *
 * ⚠️ นับเป็น **รายคำขอ ไม่ใช่รายเลขพัสดุ**
 *
 * เราไม่ได้เก็บเลขพัสดุไว้ (และจะไม่เก็บ — ดู 0007) จึงแยกไม่ออกว่าเลขเดิมที่
 * คนกดค้นซ้ำสามครั้งคือเลขเดียวหรือสามเลข ตัวเลขนี้จึงเป็น **เพดานบน** ของ
 * จำนวนเลขที่กลไกเดาขนส่งจะช่วยได้ ไม่ใช่จำนวนจริง ห้ามเอาไปคูณราคาต่อครั้ง
 * ตรงๆ แล้วสรุปว่าโควตาพอหรือไม่พอ
 *
 * p_days = 0 แปลว่า "ตั้งแต่ต้น" เหมือนฟังก์ชันอื่นในชุดนี้
 */
create or replace function public.admin_unknown_courier_failures(p_days integer)
returns bigint
language sql
stable
as $$
  select count(*)
  from public.search_events
  where unknown_courier
    and (p_days <= 0 or occurred_at >= now() - make_interval(days => p_days));
$$;

-- ------------------------------------------------------------------ --
-- สิทธิ์ — กติกาเดียวกับตารางของกลางอื่นทุกประการ
-- ------------------------------------------------------------------ --

revoke all on function public.admin_unknown_courier_failures(integer) from anon, authenticated, public;

grant execute on function public.admin_unknown_courier_failures(integer) to service_role;

