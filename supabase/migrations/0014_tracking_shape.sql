-- เก็บ "รูปแบบ" ของเลขที่ค้นไม่เจอ เพื่อให้รู้ก่อนที่ผู้ใช้จะมาแจ้ง
--
-- ปัญหาที่แก้: เลข JTTH203388775531 ค้นไม่เจอมาตลอดเพราะ JTTH ไม่มีในตาราง
-- prefix แต่เราไม่มีทางรู้เลย เพราะเราไม่เก็บเลขพัสดุ (ตั้งใจ ดู 0007) จึงต้อง
-- รอให้ผู้ใช้มาแจ้งเอง — ซึ่งแปลว่าปัญหาแบบเดียวกันของขนส่งเจ้าอื่นอาจกำลัง
-- เกิดอยู่ตอนนี้โดยไม่มีใครรู้
--
-- ------------------------------------------------------------------ --
-- ⚠️ ทำไมการเก็บ "รูปแบบ" ไม่ขัดกับคำสัญญาบนหัวหน้า
--
-- คำสัญญาคือ **ห้ามมีทางใดที่ทำให้ตอบได้ว่า "ผู้ใช้คนไหนค้นพัสดุอะไร"**
--
-- ค่าที่เก็บคือผลของ trackingShape() (lib/tracking-shape.ts) ซึ่ง:
--   ตัวเลขทุกตัว   → "#"   ข้อมูลหายหมด
--   ตัวอักษรท้าย   → "A"   ข้อมูลหายหมด
--   ตัวอักษรนำหน้า → เก็บไว้ไม่เกิน 4 ตัว
--
-- สิ่งเดียวที่เหลือคือ prefix ของขนส่ง ซึ่งพัสดุทุกใบของเจ้านั้นใช้ร่วมกัน —
-- ข้อมูลระดับเดียวกับคอลัมน์ carrier_code ที่เก็บอยู่แล้วตั้งแต่ 0007
-- "เวลา 14:03 มีคนค้นเลขทรง JTTH############" บอกไม่ได้ว่าใครค้น และบอกไม่ได้
-- ว่าเลขอะไร เพราะเลข J&T ทุกใบในประเทศให้รูปแบบเดียวกันหมด
--
-- ยังไม่มี user_id ไม่มีอีเมล ไม่มีเลขพัสดุ ฟังก์ชันคืนได้แค่ตัวเลขรวม
-- มีเทสต์เฝ้าอยู่ที่ lib/tracking-shape.test.ts และ lib/admin-privacy.test.ts
-- ------------------------------------------------------------------ --

alter table public.search_events
  add column if not exists tracking_shape text;

/*
 * รูปแบบเลขที่ค้นไม่เจอบ่อยที่สุด
 *
 * นับเฉพาะ outcome = 'not_found' เพราะนี่คือคำถามเดียวที่คอลัมน์นี้มีไว้ตอบ:
 * "ทรงไหนที่ระบบตามไม่ได้" ส่วนทรงที่ค้นเจอปกติไม่ต้องรู้
 *
 * ⚠️ ตัวเลขนี้อ่านเป็น "เพดานบน" เสมอ — คนที่พิมพ์เลขผิดก็ถูกนับด้วย และเรา
 * แยกไม่ออกจากเลขที่ถูกต้องแต่ระบบตามไม่ได้ สิ่งที่ตัวเลขนี้ทำได้จริงคือ
 * ชี้ว่า "ทรงนี้โผล่บ่อยผิดปกติ ไปตรวจดู" ไม่ใช่พิสูจน์ว่ามีบั๊ก
 */
create or replace function public.admin_unfound_shapes(
  p_days integer,
  p_limit integer
) returns table (tracking_shape text, total bigint)
language sql
stable
as $$
  select tracking_shape, count(*) as total
  from public.search_events
  where outcome = 'not_found'
    and tracking_shape is not null
    and (p_days <= 0 or occurred_at >= now() - make_interval(days => p_days))
  group by tracking_shape
  order by count(*) desc, tracking_shape
  limit greatest(coalesce(p_limit, 10), 1);
$$;

-- ------------------------------------------------------------------ --
-- สิทธิ์ — กติกาเดียวกับตารางของกลางอื่นทุกประการ
-- ------------------------------------------------------------------ --

revoke all on function public.admin_unfound_shapes(integer, integer) from anon, authenticated, public;

grant execute on function public.admin_unfound_shapes(integer, integer) to service_role;

