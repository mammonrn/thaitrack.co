-- สวิตช์เปิด/ปิดฟีเจอร์จากหลังบ้าน โดยไม่ต้อง deploy ใหม่
--
-- ปัญหาที่แก้: การปิดแผนที่ตอนนี้ทำได้ทางเดียวคือแก้โค้ดแล้ว deploy ซึ่งใช้เวลา
-- หลายนาทีและต้อง restart โปรเซส ถ้าวันไหนโควตา Google หมดกลางวัน หรือแผนที่
-- แสดงผลผิดจนต้องปิดด่วน เราไม่มีปุ่มให้กด
--
-- ------------------------------------------------------------------ --
-- ⚠️ ทำไมเป็น jsonb ไม่ใช่คอลัมน์ boolean ต่อฟีเจอร์
--
-- ตารางที่มีคอลัมน์ต่อฟีเจอร์จะต้องรัน migration ทุกครั้งที่เพิ่มสวิตช์ตัวใหม่
-- ซึ่งขัดกับเหตุผลที่สร้างตารางนี้ตั้งแต่แรก (อยากได้ปุ่มที่กดได้ทันที)
-- key/value แบบ jsonb ทำให้สวิตช์ตัวถัดไปเป็นแค่การ insert หนึ่งแถว
--
-- ราคาที่จ่ายคือ "ค่าอะไรก็ใส่ได้" — จึงต้องมีชุดคีย์ปิดฝั่งแอป (ดู
-- lib/app-settings.ts) ที่ปฏิเสธคีย์นอกรายการและบังคับชนิดของค่าก่อนเขียนเสมอ
-- ฐานข้อมูลเก็บได้ทุกอย่าง แต่แอปยอมรับเฉพาะที่รู้จัก
--
-- ⚠️ ตารางนี้ **ไม่ใช่ที่เก็บความลับ** ห้ามเอา API key หรือ secret มาไว้ที่นี่
-- ค่าที่อยู่ในนี้ถูกอ่านโดยเส้นทางแสดงผลปกติ และบางค่าจะสะท้อนออกไปถึงหน้าเว็บ
-- ของที่เป็นความลับอยู่ใน env เท่านั้นเหมือนเดิม
-- ------------------------------------------------------------------ --

create table if not exists public.app_settings (
  -- ชื่อสวิตช์ เช่น 'map_enabled' — ชุดปิดที่ฝั่งแอปรู้จัก
  key text primary key,

  -- ค่าเป็น jsonb เพื่อให้สวิตช์ในอนาคตเก็บได้มากกว่า true/false
  value jsonb not null,

  -- ไว้ดูว่าใครเปลี่ยนเมื่อไร (เก็บแค่เวลา ไม่เก็บว่าใคร — ดูหมายเหตุข้างล่าง)
  updated_at timestamptz not null default now()
);

-- ------------------------------------------------------------------ --
-- ตั้งใจ **ไม่เก็บว่าแอดมินคนไหนเป็นคนกด**
--
-- ระบบนี้ไม่เคยเก็บว่าใครทำอะไรเลยแม้แต่ที่เดียว (ดูข้อบังคับใน 0007) และการ
-- เริ่มเก็บที่ตารางนี้จะเป็นข้อยกเว้นแรก ซึ่งเปิดประตูให้ข้อยกเว้นถัดไป
-- ถ้าวันหนึ่งต้องรู้จริงๆ ว่าใครกด ให้ไปดู log ของเซิร์ฟเวอร์ ไม่ใช่เก็บลงตาราง
-- ------------------------------------------------------------------ --

-- ------------------------------------------------------------------ --
-- สิทธิ์ — กติกาเดียวกับตารางของกลางทุกตาราง (ดู 0004 และ 0005)
--
-- สองชั้นที่ซ้อนกัน:
--   1. revoke สิทธิ์จาก anon/authenticated ทิ้งให้หมด
--   2. เปิด RLS โดยไม่สร้าง policy ใดเลย → Postgres ปฏิเสธทุกแถวเป็นค่าเริ่มต้น
--      service_role ข้าม RLS ได้อยู่แล้วจึงทำงานตามปกติ
--
-- หน้า /admin/stats ไม่ได้ยิงเข้าตารางนี้ตรงๆ จากเบราว์เซอร์ — มันเรียก
-- API route ของเราที่ตรวจสิทธิ์แอดมินฝั่งเซิร์ฟเวอร์ก่อนเสมอ
--
-- ⚠️ ไม่ให้สิทธิ์ delete — การลบแถวจะทำให้ค่ากลับไปเป็นค่าเริ่มต้นแบบเงียบๆ
-- ซึ่งเป็นการ "เปลี่ยนค่า" ที่มองไม่เห็น การปิดสวิตช์ต้องเป็นการเขียน false
-- ลงไปตรงๆ ไม่ใช่การทำให้แถวหายไป
-- ------------------------------------------------------------------ --

revoke all on table public.app_settings from anon;
revoke all on table public.app_settings from authenticated;

grant select, insert, update on table public.app_settings to service_role;

alter table public.app_settings enable row level security;

-- ไม่มี create policy ที่นี่โดยตั้งใจ (เหตุผลเดียวกับ 0004)

-- ------------------------------------------------------------------ --
-- ค่าเริ่มต้น
--
-- map_enabled = false ตามที่ตัดสินใจไว้ — เปิดเมื่อพร้อมด้วยปุ่มบนหน้าแอดมิน
--
-- on conflict do nothing เพื่อให้รันไฟล์นี้ซ้ำได้โดยไม่เขียนทับค่าที่แอดมิน
-- ตั้งไว้แล้ว — migration ที่รันซ้ำแล้วรีเซ็ตสวิตช์ของคนอื่นคือกับดัก
-- ------------------------------------------------------------------ --

insert into public.app_settings (key, value)
values ('map_enabled', 'false'::jsonb)
on conflict (key) do nothing;

