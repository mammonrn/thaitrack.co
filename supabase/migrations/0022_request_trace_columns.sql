-- ── ช่องว่างที่ปิด ────────────────────────────────────────────────
-- เดิมเรามีแค่ took_ms ซึ่งบอกว่าคำขอหนึ่งใช้เวลาเท่าไร แต่ไม่บอกว่าเวลานั้น
-- หมดไปกับอะไร ตอนวิเคราะห์ว่าทำไม not_found ถึงใช้เวลา p95 12.5 วินาที เรา
-- ต้องไปนับบรรทัด [track123] ใน pm2 log เอาเอง ซึ่งทำได้เพราะบังเอิญยังไม่ถูก
-- rotate ทิ้ง และทำได้เฉพาะเจ้าที่มี log บรรทัดต่อ request เท่านั้น
--
-- สองคอลัมน์นี้แยกคำถามที่แก้คนละทางออกจากกัน:
--
--   upstream_calls สูง + queue_ms ต่ำ   → ยิงหลายครั้งเกินไป · แก้ที่จำนวนครั้ง
--   upstream_calls ต่ำ  + queue_ms สูง   → คิวฝั่งเราแคบ · เพิ่ม concurrency ได้ฟรี
--   ทั้งคู่ต่ำ แต่ took_ms สูง          → ปลายทางอืดเอง · ทำอะไรไม่ได้นอกจากตัด
--
-- ⚠️ ข้อบังคับความเป็นส่วนตัวเหมือนเดิมทุกประการ — ทั้งสองคอลัมน์เป็นตัวเลข
-- ล้วนๆ ที่เป็นคุณสมบัติของคำขอ ไม่ได้บอกอะไรเกี่ยวกับคนที่ค้นเลย และ
-- search_events ยังไม่มี user id ไม่มี IP ไม่มีเลขพัสดุเหมือนเดิม (ดู 0007)
--
-- ⚠️ ทั้งคู่ nullable โดยตั้งใจ · แถวเก่าทั้งหมดเป็น null ซึ่งแปลว่า "ไม่รู้"
-- ไม่ใช่ "ศูนย์ครั้ง" การใส่ default 0 จะทำให้ค่าเฉลี่ยย้อนหลังผิดทันที
-- ------------------------------------------------------------------ --

alter table public.search_events
  add column if not exists upstream_calls integer,
  add column if not exists queue_ms integer;

comment on column public.search_events.upstream_calls is
  'จำนวนครั้งที่ยิงถามขนส่งจริงในคำขอนี้ รวมทุกเจ้าและทุกการลองซ้ำ · null = แถวเก่าก่อนมีคอลัมน์นี้';

comment on column public.search_events.queue_ms is
  'เวลาที่รออยู่ในคิวฝั่งเราก่อนได้ยิงจริง (ms) รวมทุกครั้งในคำขอนี้ · null = แถวเก่าก่อนมีคอลัมน์นี้';

