-- นับว่าปุ่ม "ลองอีกครั้ง" ได้ผลไหม
--
-- ── ปัญหาที่ตอบ ───────────────────────────────────────────────────
-- upstream_error เกิด 1–3 ครั้งทุกวันไม่มีเว้น (32 ครั้งใน 6 วัน) และมีหลักฐาน
-- ว่าคนที่กดลองใหม่ได้คำตอบ — เช่นเลข LEXPU0709539718 ล้ม 3 ครั้งใน 33 วินาที
-- แล้วครั้งที่ 4 สำเร็จ · แต่คนที่ยอมแพ้ก่อนหน้านั้นเสียไปฟรีๆ
--
-- ปุ่มลองอีกครั้งจึงถูกเพิ่มเข้ามา และต้องวัดได้ว่ามันช่วยจริงไหม ไม่งั้นเรา
-- จะไม่มีทางรู้ว่าควรเก็บไว้ ปรับ หรือถอดทิ้ง
--
-- ── ทำไมเป็นคอลัมน์ในตารางเดิม ไม่ใช่ตารางใหม่ ────────────────────
-- การกดปุ่มลองอีกครั้ง **คือการค้นหาหนึ่งครั้ง** ทุกประการ — มันวิ่งผ่าน
-- /api/track เส้นทางเดียวกัน ได้ผลแบบเดียวกัน และควรถูกนับรวมในสถิติการค้นหา
-- อยู่แล้ว · สิ่งเดียวที่ต่างคือ "คำขอนี้มาจากการกดปุ่มหรือจากการค้นครั้งแรก"
-- ซึ่งเป็นคุณสมบัติของคำขอ = คอลัมน์ ไม่ใช่ตาราง
--
-- ตัวเลขสามตัวที่ต้องการอ่านได้จากคอลัมน์เดียวนี้ทั้งหมด:
--   แสดงปุ่มกี่ครั้ง = count(*) where reason = 'upstream_error'
--   กดกี่ครั้ง       = count(*) where retried
--   สำเร็จกี่ครั้ง    = count(*) where retried and outcome = 'found'
--
-- ⚠️ ข้อบังคับความเป็นส่วนตัวเหมือนเดิมทุกประการ — เป็น boolean ที่บอกว่า
-- "คำขอนี้มาจากการกดปุ่ม" ไม่ได้บอกอะไรเกี่ยวกับคนที่กดเลย และ search_events
-- ยังไม่มี user id ไม่มี IP ไม่มีเลขพัสดุเหมือนเดิม (ดู 0007)
--
-- ⚠️ default false ไม่ใช่ null — แถวเก่าทั้งหมดเกิดในยุคที่ยังไม่มีปุ่ม
-- "ไม่ได้มาจากการกดปุ่ม" จึงเป็นค่าที่ถูกต้องจริงๆ ไม่ใช่การเดา
-- ------------------------------------------------------------------ --

alter table public.search_events
  add column if not exists retried boolean not null default false;

comment on column public.search_events.retried is
  'true = คำขอนี้มาจากการกดปุ่ม "ลองอีกครั้ง" หลังเจอ upstream_error · แถวก่อน 2026-09 เป็น false ทั้งหมดตามพฤติกรรมเดิม';

